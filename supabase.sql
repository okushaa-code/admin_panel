-- ---------------------------------------------------------------------------
-- Админ самбарын нэмэлт хамгаалалт ба индекс (давтан ажиллуулахад аюулгүй)
-- ---------------------------------------------------------------------------

-- Цаг товлолтын төлөвийг зөвхөн зөвшөөрөгдсөн утгаар хязгаарлана.
-- NOT VALID: одоо байгаа мөрүүдийг шалгахгүй, зөвхөн шинэ/өөрчлөгдөх мөрөнд үйлчилнэ.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'bookings_status_check'
          AND conrelid = 'public.bookings'::regclass
    ) THEN
        ALTER TABLE public.bookings
            ADD CONSTRAINT bookings_status_check
            CHECK (status IN ('pending', 'approved', 'rejected')) NOT VALID;
    END IF;
END $$;

-- Жагсаалтыг огноогоор эрэмбэлэх, төлөвөөр шүүхэд зориулсан индексүүд.
CREATE INDEX IF NOT EXISTS bookings_scheduled_at_idx ON public.bookings (scheduled_at);
CREATE INDEX IF NOT EXISTS bookings_status_idx ON public.bookings (status);
CREATE INDEX IF NOT EXISTS customer_messages_created_at_idx ON public.customer_messages (created_at DESC);
CREATE INDEX IF NOT EXISTS customer_messages_status_idx ON public.customer_messages (status);
CREATE INDEX IF NOT EXISTS content_drafts_created_at_idx ON public.content_drafts (created_at DESC);
CREATE INDEX IF NOT EXISTS properties_for_sale_created_at_idx ON public.properties_for_sale (created_at DESC);
CREATE INDEX IF NOT EXISTS properties_for_rent_created_at_idx ON public.properties_for_rent (created_at DESC);

-- Нууц үгийн хэш агуулсан users хүснэгтийг браузерын (anon/authenticated)
-- түлхүүрээр хэзээ ч уншиж болохгүй. Админ самбар нь зөвхөн сервер талд
-- service-role түлхүүр ашиглах тул энэ хязгаарлалтад өртөхгүй.
