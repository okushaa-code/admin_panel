CREATE TABLE IF NOT EXISTS public.content_drafts (
    id integer PRIMARY KEY,
    title text NOT NULL,
    content text NOT NULL,
    status text NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS public.bookings (
    id integer PRIMARY KEY,
    customer_name text NOT NULL,
    email text NOT NULL,
    phone text NOT NULL,
    scheduled_at timestamptz NOT NULL,
    notes text
);

ALTER TABLE public.bookings
    ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'pending';

CREATE TABLE IF NOT EXISTS public.properties_for_sale (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    location text NOT NULL,
    price bigint NOT NULL CHECK (price > 0),
    area_sqm numeric(10, 2) NOT NULL CHECK (area_sqm > 0),
    bedrooms integer NOT NULL CHECK (bedrooms BETWEEN 0 AND 30),
    description text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (title, location)
);

CREATE TABLE IF NOT EXISTS public.properties_for_rent (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    location text NOT NULL,
    price bigint NOT NULL CHECK (price > 0),
    area_sqm numeric(10, 2) NOT NULL CHECK (area_sqm > 0),
    bedrooms integer NOT NULL CHECK (bedrooms BETWEEN 0 AND 30),
    description text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (title, location)
);

CREATE TABLE IF NOT EXISTS public.customer_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_name text NOT NULL,
    email text NOT NULL,
    phone text NOT NULL DEFAULT '',
    subject text NOT NULL,
    content text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    status text NOT NULL DEFAULT 'unread'
        CHECK (status IN ('unread', 'read', 'archived'))
);

CREATE TABLE IF NOT EXISTS public.users (
    id integer PRIMARY KEY,
    email text NOT NULL UNIQUE,
    password_hash text NOT NULL
);

